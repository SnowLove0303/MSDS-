def standardize_component_name(raw_name: str, cas: str = "") -> str:
    """将 Section 3 原始成分名称转换为统一标准名称.

    逻辑:
    1. 若提供了标准 CAS 号且在 CAS 字典中，直接返回该 CAS 对应的标准成分名；
    2. 若命中名称别名映射表，返回标准化别名；
    3. 剥离前后空格与特殊冒号后返回。
    """
    raw = (raw_name or "").strip()
    if not raw:
        return ""

    # 清理 CAS
    clean_cas = re.sub(r"[^\d\-]", "", cas or "")
    if clean_cas in CAS_TO_STANDARD_NAME:
        return CAS_TO_STANDARD_NAME[clean_cas]

    # 直接名称匹配
    if raw in NAME_ALIAS_MAPPING:
        return NAME_ALIAS_MAPPING[raw]

    # 压缩空白后匹配
    compact = re.sub(r"\s+", "", raw)
    for k, v in NAME_ALIAS_MAPPING.items():
        if re.sub(r"\s+", "", k) == compact:
            return v

    return raw
